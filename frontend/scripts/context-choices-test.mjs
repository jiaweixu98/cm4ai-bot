import assert from 'node:assert/strict';
import { selectPublications, removePublication, useEligiblePublications, contextChoicesForRequest } from '../app/lib/contextChoices.mjs';
const paper={author_id:'123',work_id:'W1',title:'A real selection'};
const original={publicationScope:'eligible',publicationFilters:[{author_id:'123',affiliation:'A'}],samePlace:false,recentYears:0,paperScope:'chosen'};
const selected=selectPublications(original,[paper]);
assert.equal(selected.publicationScope,'selected');
const removed=removePublication(selected,paper);
assert.equal(removed.selectedPapers.length,0);
assert.equal(removed.publicationScope,'selected');
const sent=contextChoicesForRequest(removed);
assert.equal(sent.publication_scope,'selected');
assert.deepEqual(sent.selected_publications,[]);
assert.deepEqual(sent.publication_filters,original.publicationFilters);
const restored=JSON.parse(JSON.stringify(removed));
assert.equal(contextChoicesForRequest(restored).publication_scope,'selected');
assert.equal(contextChoicesForRequest(useEligiblePublications(removed)).publication_scope,'eligible');
assert.equal(selectPublications(original,Array.from({length:10},(_,i)=>({...paper,work_id:`W${i}`}))).selectedPapers.length,8);
assert.deepEqual(contextChoicesForRequest(selected).selected_publications,[{author_id:'123',work_id:'W1'}]);
assert.equal(removePublication(selectPublications(original,[paper,{...paper,author_id:'456'}]),paper).selectedPapers[0].author_id,'456');
console.log('PASS explicit empty selection through removal, serialization and restore; explicit eligible reset; filters, author-specific keys, eight-paper limit');
