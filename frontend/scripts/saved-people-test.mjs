import assert from 'node:assert/strict';
import { accountSavedPeople } from '../app/lib/savedPeople.mjs';
import { readAttachedFiles } from '../app/lib/attachedPapers.js';
let calls = [];
globalThis.fetch = async (path, options) => {
  calls.push({ path, options });
  return new Response(JSON.stringify({ people: [{ authorId: 42 }] }));
};
assert.equal((await accountSavedPeople()).people[0].authorId, 42);
assert.equal(calls[0].path, '/api/saved-people');
await accountSavedPeople('/42', { method: 'DELETE', body: JSON.stringify({ deletedAt: '2026-01-01T00:00:00Z' }) });
assert.equal(calls[1].options.method, 'DELETE');
globalThis.fetch = async () => new Response('', { status: 401 });
await assert.rejects(accountSavedPeople, /Sign in on the graph/);
globalThis.fetch = async () => new Response('', { status: 403 });
await assert.rejects(accountSavedPeople, /Could not update/);
console.log('PASS standalone saved-people endpoint, delete, authentication and failure feedback');
globalThis.FileReader = class { readAsDataURL() { this.result = 'data:application/pdf;base64,AAAA'; this.onload(); } };
globalThis.fetch = async () => new Response('', { status: 413 });
let result = await readAttachedFiles([{ name: 'supported.pdf', size: 850000 }]);
assert.equal(result.failedRead, 1);
assert.equal(result.skippedType, 0);
assert.equal(result.skippedSize, 0);
result = await readAttachedFiles([{ name: 'too-large.pdf', size: 11 * 1024 * 1024 }, { name: 'unsupported.exe', size: 1 }]);
assert.equal(result.skippedSize, 1);
assert.equal(result.skippedType, 1);
assert.equal(result.failedRead, 0);
result = await readAttachedFiles([{ name: 'context.txt', size: 30, text: async () => 'Research context for a test.' }]);
