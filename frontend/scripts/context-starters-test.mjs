import assert from 'node:assert/strict';
import {contextStarters} from '../app/lib/contextStarters.mjs';
const text = opts => JSON.stringify(contextStarters(opts));
assert.equal(contextStarters().length,6);
assert.match(text(), /AI-ready data standards/);
assert.match(text(), /sepsis early-warning/);
assert.doesNotMatch(text(), /First ask|do not assume|Support recommendations|Use the eligible|\\\\n/);
const personalContext={interests:'rare topic XYZ',useInterests:true,contacts:[{name:'Included Person',included:true},{name:'Excluded Person',included:false}]};
assert.match(text({choices:{personalContext}}), /rare topic XYZ/);
assert.doesNotMatch(text({choices:{personalContext}}), /Included Person/);
assert.doesNotMatch(text({choices:{personalContext}}), /Excluded Person/);
assert.doesNotMatch(text({choices:{personalContext:{...personalContext,useInterests:false}}}), /rare topic XYZ/);
assert.doesNotMatch(text({choices:{personalContext}}), /self-reported|availability/);
const people=[{authorId:1,name:'Not selected'},{authorId:2,name:'Selected Person'}];
assert.match(text({people,personIds:[2]}), /Selected Person/);
assert.doesNotMatch(text({people,personIds:[2]}), /Not selected/);
assert.match(text({linked:true,profileName:'Linked Author'}), /Linked Author/);
assert.match(contextStarters({linked:true,profileName:'Linked Author'})[3].prompt, /my top 10 recorded coauthors/);
assert.match(contextStarters({linked:true,profileName:'Linked Author',people,personIds:[2]})[3].prompt, /my top 10 recorded coauthors/);
assert.doesNotMatch(text({linked:false,profileName:'Previous User'}), /Previous User/);
assert.doesNotMatch(text({linked:true,profileName:'Linked Author',choices:{publicationScope:'selected',selectedPapers:[]}}), /publications associated/);
assert.match(contextStarters({choices:{publicationScope:'selected',selectedPapers:[{title:'Chosen Paper'}]}})[5].prompt, /first paper I've selected/);
assert.doesNotMatch(text({choices:{publicationScope:'eligible',selectedPapers:[{title:'Stale Paper'}]}}), /Stale Paper/);
assert.equal(contextStarters().every(s=>s.basis && s.prompt && s.label),true);
console.log('PASS scientific editable examples, opted-in interests, selected person identity, linked profile, empty publication scope, selected-paper audience and no instruction preambles');

const labels=['Find a mentor','Build a team','Find a niche','Explore','Collaborate','Promote'];
for (const options of [{},{choices:{personalContext}},{linked:true,profileName:'Author'},{choices:{publicationScope:'selected',selectedPapers:[]}}]) assert.deepEqual(contextStarters(options).map(s=>s.label),labels);
console.log('PASS all six workflows retained for empty, personalized, linked and empty-publication accounts');
